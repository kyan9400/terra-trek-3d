function toPoly(pts: number[]): Poly {
  let minLon = 999, maxLon = -999, minLat = 999, maxLat = -999;
  for (let i = 0; i < pts.length; i += 2) {
    minLon = Math.min(minLon, pts[i]);
    maxLon = Math.max(maxLon, pts[i]);
    minLat = Math.min(minLat, pts[i + 1]);
    maxLat = Math.max(maxLat, pts[i + 1]);
  }
  return { pts, minLon, maxLon, minLat, maxLat };
}

const LAND = LAND_RAW.map(toPoly);
const WATER = WATER_RAW.map(toPoly);

// Ray casting in lon/lat space (fine away from the poles, which the latitude rule covers)
function inside(p: Poly, lon: number, lat: number) {
  if (lon < p.minLon || lon > p.maxLon || lat < p.minLat || lat > p.maxLat) return false;
  const pts = p.pts;
  let hit = false;
  for (let i = 0, j = pts.length - 2; i < pts.length; j = i, i += 2) {
    const xi = pts[i], yi = pts[i + 1], xj = pts[j], yj = pts[j + 1];
    if (yi > lat !== yj > lat && lon < ((xj - xi) * (lat - yi)) / (yj - yi) + xi) hit = !hit;
  }
  return hit;
}

export function isLand(lon: number, lat: number) {
  // Antarctic ice sheet: a wavy latitude line instead of a polygon
  if (lat < -71 + 3.5 * Math.sin((lon * Math.PI) / 90) + 1.5 * Math.cos((lon * Math.PI) / 45)) return true;
  let land = false;
  for (const p of LAND) {
    if (inside(p, lon, lat)) {
      land = true;
      break;
    }
  }
  if (!land) return false;
  for (const w of WATER) if (inside(w, lon, lat)) return false;
  return true;
}
